int add(int num_1, int num_2) { return ( num_1 + num_2 ); }
int sub(int num_1, int num_2) { return ( num_1 - num_2 ); }
int mult(int num_1, int num_2) { return ( num_1 * num_2 ); }
int divide(int num_1, int num_2) { return ( num_1 / num_2 ); }
int mod(int num_1, int num_2) { return ( num_1 % num_2 ); }